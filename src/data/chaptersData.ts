export function getChaptersBySubject(classLevel: ClassLevel, subjectCode: string): ChapterItem[] {
  return ALL_CHAPTERS_DATA.filter(
    (ch) => ch.classLevel === classLevel && ch.subjectCode.toLowerCase() === subjectCode.toLowerCase()
  );
}

/**
 * Generate a YouTube search URL for the chapter if specific URL is not set
 */
export function getChapterYouTubeLink(chapter: ChapterItem): string {
  if (chapter.youtubeUrl && !chapter.youtubeUrl.includes('search_query')) {
    return chapter.youtubeUrl;
  }
  const query = encodeURIComponent(`UP Board ${chapter.classLevel} ${chapter.titleHindi} ${chapter.title} One Shot lecture`);
  return `https://www.youtube.com/results?search_query=${query}`;
}
